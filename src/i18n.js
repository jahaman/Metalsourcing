export function translator(lang) {
	const table = STRINGS[lang] || STRINGS.en;

	return (key, ...args) => {
		let text = table[key] ?? STRINGS.en[key] ?? key;

		args.forEach(arg => { text = text.replace('%s', arg); });

		return text;
	};
}
